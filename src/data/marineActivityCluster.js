function mergeEnhancement(page, enhancement = {}) {
  const { relatedAppend = [], sectionsAppend = [], ...rest } = enhancement;
  return {
    ...page,
    ...rest,
    sections: [...(page.sections ?? []), ...sectionsAppend],
    related: [...(page.related ?? []), ...relatedAppend],
  };
}

export function enhanceMarineCluster(basePages, destination) {
  const enhancements = destination === 'phu-quoc' ? phuEnhancements : nhaEnhancements;
  const additions = destination === 'phu-quoc' ? phuQuocMarinePages : nhaTrangMarinePages;
  const enhanced = Object.fromEntries(
    Object.entries(basePages).map(([slug, page]) => [slug, mergeEnhancement(page, enhancements[slug])])
  );
  return { ...enhanced, ...additions };
}
